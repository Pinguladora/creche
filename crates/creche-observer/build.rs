//! Compiles the BPF programs with clang into `$OUT_DIR/observer.bpf.o`.
//!
//! `-g` makes clang emit BTF, which carries the CO-RE relocations the loader
//! resolves against the running kernel. Set `CLANG` to use a specific clang.
//!
//! The C wire structs (`bpf/wire.h`) must match `creche-wire` byte for byte, so
//! this also generates C static assertions from the Rust layout: any drift
//! fails the build.

use std::env;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::mem::{offset_of, size_of};
use std::path::{Path, PathBuf};
use std::process::Command;

use creche_wire::{
    ConnectRecord, ExecRecord, ExitRecord, ForkRecord, Header, OpenRecord, TaskRecord,
};

/// C assertions that the structs in `wire.h` have the Rust layout.
fn layout_checks() -> Result<String, std::fmt::Error> {
    let sizes = [
        ("ev_hdr", size_of::<Header>()),
        ("ev_task", size_of::<TaskRecord>()),
        ("ev_fork", size_of::<ForkRecord>()),
        ("ev_exit", size_of::<ExitRecord>()),
        ("ev_connect", size_of::<ConnectRecord>()),
        ("ev_open", size_of::<OpenRecord>()),
        ("ev_exec", size_of::<ExecRecord>()),
    ];
    let offsets = [
        ("ev_hdr", "kind", offset_of!(Header, kind)),
        ("ev_hdr", "len", offset_of!(Header, len)),
        ("ev_hdr", "pid", offset_of!(Header, pid)),
        ("ev_hdr", "ts_ns", offset_of!(Header, ts_ns)),
        ("ev_task", "ppid", offset_of!(TaskRecord, ppid)),
        ("ev_task", "uid", offset_of!(TaskRecord, uid)),
        ("ev_task", "cgroup_id", offset_of!(TaskRecord, cgroup_id)),
        ("ev_task", "comm", offset_of!(TaskRecord, comm)),
        ("ev_task", "cgroup", offset_of!(TaskRecord, cgroup)),
        ("ev_fork", "ppid", offset_of!(ForkRecord, ppid)),
        ("ev_fork", "reserved", offset_of!(ForkRecord, reserved)),
        ("ev_exit", "exit_code", offset_of!(ExitRecord, exit_code)),
        ("ev_exit", "reserved", offset_of!(ExitRecord, reserved)),
        ("ev_connect", "family", offset_of!(ConnectRecord, family)),
        ("ev_connect", "dport", offset_of!(ConnectRecord, dport)),
        ("ev_connect", "daddr", offset_of!(ConnectRecord, daddr)),
        (
            "ev_connect",
            "reserved",
            offset_of!(ConnectRecord, reserved),
        ),
        ("ev_open", "path_len", offset_of!(OpenRecord, path_len)),
        ("ev_open", "path", offset_of!(OpenRecord, path)),
        ("ev_exec", "ppid", offset_of!(ExecRecord, ppid)),
        ("ev_exec", "uid", offset_of!(ExecRecord, uid)),
        ("ev_exec", "cgroup_id", offset_of!(ExecRecord, cgroup_id)),
        ("ev_exec", "comm", offset_of!(ExecRecord, comm)),
        ("ev_exec", "path_len", offset_of!(ExecRecord, path_len)),
        ("ev_exec", "args_len", offset_of!(ExecRecord, args_len)),
        ("ev_exec", "data", offset_of!(ExecRecord, data)),
    ];
    let mut c = String::from(
        "/* Generated by build.rs from crate creche-wire. */\n#include <linux/types.h>\n#include \"wire.h\"\n",
    );
    for (ty, size) in sizes {
        writeln!(
            c,
            "_Static_assert(sizeof(struct {ty}) == {size}, \"struct {ty} differs from creche-wire\");"
        )?;
    }
    for (ty, field, offset) in offsets {
        writeln!(
            c,
            "_Static_assert(__builtin_offsetof(struct {ty}, {field}) == {offset}, \"{ty}.{field} differs from creche-wire\");"
        )?;
    }
    Ok(c)
}

fn main() -> Result<(), Box<dyn Error>> {
    let bpf_dir = Path::new("bpf");
    for file in ["observer.bpf.c", "creche.h", "wire.h"] {
        println!("cargo::rerun-if-changed={}", bpf_dir.join(file).display());
    }
    println!("cargo::rerun-if-env-changed=CLANG");

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").ok_or("OUT_DIR not set")?);
    let checks = out_dir.join("layout_checks.h");
    fs::write(&checks, layout_checks()?)?;
    let out = out_dir.join("observer.bpf.o");
    let clang = env::var_os("CLANG").unwrap_or_else(|| "clang".into());
    let mut cmd = Command::new(&clang);
    cmd.args([
        "-target", "bpf", "-mcpu=v3", "-O2", "-g", "-Wall", "-Werror",
    ])
    .arg("-I")
    .arg(bpf_dir);
    // Debian and Ubuntu keep <asm/...> under the multiarch include directory.
    let multiarch =
        Path::new("/usr/include").join(format!("{}-linux-gnu", env::var("CARGO_CFG_TARGET_ARCH")?));
    if multiarch.is_dir() {
        cmd.arg("-I").arg(multiarch);
    }
    cmd.arg("-c")
        .arg(bpf_dir.join("observer.bpf.c"))
        .arg("-o")
        .arg(&out);
    cmd.arg("-include").arg(&checks);

    let status = cmd.status().map_err(|e| {
        format!(
            "running {}: {e} (install clang, or set CLANG)",
            clang.to_string_lossy()
        )
    })?;
    if !status.success() {
        return Err(format!("compiling the BPF programs failed: {status}").into());
    }
    Ok(())
}
